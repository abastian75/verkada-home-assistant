/* Run after serving the repository at http://127.0.0.1:8769. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8769/tests/frontend_fixture.html');
  await page.getByText('Driveway · Live',{exact:true}).waitFor();
  await page.waitForFunction(()=>window.fixtureCalls.some(c=>c.type==='camera/stream'));
  assert.equal(await page.getByRole('button',{name:'Live view',exact:true}).count(),0);
  const output=process.env.UI_OUTPUT;
  if(output)await page.screenshot({path:path.join(output,'desktop-live.png'),fullPage:true});
  await page.getByRole('button',{name:'Events & recordings',exact:true}).click();
  await page.getByText('TEST123',{exact:false}).waitFor();
  assert.equal(await page.locator('verkada-panel').evaluate(el=>el.shadowRoot.querySelectorAll('tbody img').length),0,'Untrusted markup became an image');
  assert.equal(await page.evaluate(()=>window.bad),undefined);
  await page.getByLabel('Search plate or event').fill('TEST123');
  assert.equal(await page.locator('verkada-panel').evaluate(el=>el.shadowRoot.querySelectorAll('tbody tr').length),1);
  await page.getByLabel('Search plate or event').fill('');
  await page.getByRole('button',{name:'Search Verkada history',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Choose Camera alerts'}).waitFor();
  await page.getByLabel('Source',{exact:true}).selectOption('lpr');
  await page.getByLabel('Camera',{exact:true}).selectOption('camera-one');
  await page.getByRole('button',{name:'Search Verkada history',exact:true}).click();
  assert.ok(await page.evaluate(()=>window.fixtureCalls.some(c=>c.action==='search'&&c.source==='lpr'&&c.camera_id==='camera-one')));
  if(output)await page.screenshot({path:path.join(output,'desktop-events.png'),fullPage:true});
  await page.getByRole('button',{name:'Watch',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Synthetic fixture'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.locator('verkada-panel').evaluate(el=>el.shadowRoot.querySelector('main').scrollWidth<=390),'Mobile main content overflows');
  if(output)await page.screenshot({path:path.join(output,'mobile-events.png'),fullPage:true});
  await page.getByRole('button',{name:'Connection',exact:true}).click();
  await page.getByText('Webhooks disabled.',{exact:false}).waitFor();
  if(output)await page.screenshot({path:path.join(output,'mobile-connection.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: desktop/mobile camera tiles, filters, source search, playback errors, webhook setup, XSS-safe event rendering');
})().catch(error=>{console.error(error);process.exit(1);});
