const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:8769/tests/cards_fixture.html');
 const lpr=page.locator('verkada-lpr-card'),events=page.locator('verkada-events-card'),camera=page.locator('verkada-camera-card');
 await lpr.getByText('TEST123',{exact:true}).first().waitFor();
 await camera.getByText(/Last plate: TEST123 · Last seen/).waitFor();
 await camera.evaluate(card=>{const hass=card._hass;hass.states[card._config.entity].attributes.last_plate='<img src=x onerror="window.bad=true">';card.hass={...hass};});
 await camera.getByText(/Last plate: <img/).waitFor();
 assert.equal(await camera.locator('#plate img').count(),0,'Plate caption executed markup');
 await camera.evaluate(card=>{const hass=card._hass;delete hass.states[card._config.entity].attributes.plate_tracking;card.hass={...hass};});
 assert.equal(await camera.locator('#plate').isVisible(),false,'Non-LPR caption is visible');
 await events.getByText('Person in driveway',{exact:true}).waitFor();
 assert.equal(await events.locator('img').count(),0,'Event markup executed');
 assert.equal(await page.evaluate(()=>window.bad),undefined);
 assert.ok(await page.evaluate(()=>window.fixtureCalls.some(c=>c.type==='verkada/stream')),'Camera did not start automatically');
 await camera.getByRole('button',{name:'Retry',exact:true}).waitFor();
 await lpr.getByRole('button',{name:'Watch recording for TEST123'}).click();
 await lpr.getByRole('alert').filter({hasText:'Synthetic fixture'}).waitFor();
 await page.getByRole('button',{name:'Edit LPR card'}).click();
 const editor=page.locator('verkada-card-editor');
 await editor.getByLabel('Camera',{exact:true}).waitFor();
 assert.deepEqual(await editor.getByLabel('Camera',{exact:true}).locator('option').allTextContents(),['All cameras','Driveway']);
 await editor.getByLabel('Title (optional)').fill('Driveway plates');
 await editor.getByLabel('Title (optional)').press('Tab');
 await lpr.getByRole('heading',{name:'Driveway plates',exact:true}).waitFor();
 if(process.env.UI_OUTPUT)await page.screenshot({path:path.join(process.env.UI_OUTPUT,'cards-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Dark theme'}).click();
 if(process.env.UI_OUTPUT)await page.screenshot({path:path.join(process.env.UI_OUTPUT,'cards-dark.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=390),'Cards overflow on mobile');
 if(process.env.UI_OUTPUT)await page.screenshot({path:path.join(process.env.UI_OUTPUT,'cards-mobile.png'),fullPage:true});
 await page.goto('http://127.0.0.1:8769/tests/cards_fixture.html?empty=1');
 await page.locator('verkada-camera-card').getByText('No plate detections yet',{exact:true}).waitFor();
 await page.locator('verkada-lpr-card').getByText(/No plate detections/).waitFor();
 await page.goto('http://127.0.0.1:8769/tests/cards_fixture.html?denied=1');
 await page.locator('verkada-lpr-card').getByRole('alert').filter({hasText:'You do not have access'}).waitFor();
 await page.goto('http://127.0.0.1:8769/tests/cards_fixture.html?registry_race=1');
 await page.locator('verkada-camera-card').getByText(/Last plate: TEST123/).waitFor();
 assert.deepEqual(errors,[]);await browser.close();
 console.log('PASS: three registered cards, automatic live startup, LPR/events, visual editor, empty/error/XSS states, desktop/mobile/light/dark');
})().catch(error=>{console.error(error);process.exit(1);});
